package ZadaniaYouTube;

public class Zad7 {
    public static void main(String[] args) {
        int i1 = 30;
        int i2 = 10;
        int i3 = 4;
        int i4 = 3;
        double i20 = 5;
        double i21 = 2;

        System.out.println("i1 + i2" + (i1+i2));
        System.out.println("i1 - i2" + (i1-i2));
        System.out.println("i1 / i2" + (i1/i2));
        System.out.println("i3 % i4" + (i3%i4));
        System.out.println("i3 * i4" + (i3*i4));
        System.out.println();
        System.out.println("Hello" + "World" + "!");

        System.out.println("i20 / i21" + (i20/i21));
        System.out.println("----------------");

        int i5 = 10;
        int i6 = -10;

        System.out.println("i5" + i5);

        System.out.println("i5++" + i5++);
        System.out.println("i5" + i5);

        System.out.println("++i5" + ++i5);
        System.out.println("i5" + i5);
        System.out.println();
        System.out.println("i6" + i6);

        System.out.println("i6--" + i6--);
        System.out.println("i6" + i6);

        System.out.println("--i6" + --i6);
        System.out.println("i6 = " + i6);
        System.out.println("-----------------------------");

        int i9 = 10;
        int i10 = 20;

        System.out.println("i9 == i10" + (i9 == i10));
        System.out.println("i9 != i10" + (i9 != i10));
        System.out.println("i9 > i10" + (i9 > i10));
        System.out.println("i9 < i10" + (i9 < i10));
        System.out.println("i9 >= i10" + (i9 >= i10));
        System.out.println("i9 <= i10" + (i9 <= i10));
        System.out.println("-----------------------");
    }
}
